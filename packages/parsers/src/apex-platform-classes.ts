const CANONICAL_BY_LOWER: ReadonlyMap<string, string> = new Map(
  PLATFORM_CLASS_NAMES.map((name) => [name.toLowerCase(), name]),
);

/**
 * The canonical spelling of a platform class or namespace `token` names, or
 * `null` when the token can be a user class.
 *
 * @example
 *   apexPlatformClassName('database') // => 'Database'
 *   apexPlatformClassName('Demo_Helper') // => null
 */
export const apexPlatformClassName = (token: string): string | null =>
  CANONICAL_BY_LOWER.get(token.toLowerCase()) ?? null;
