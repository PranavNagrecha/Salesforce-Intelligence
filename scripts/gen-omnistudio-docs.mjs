#!/usr/bin/env node
/**
 * Generate docs/omnistudio/element-catalog.md from the OmniStudio element
 * catalog (packages/extractors/src/omnistudio/catalog.ts) — the one place the
 * product describes every OmniScript element and Integration Procedure step
 * type. The document is generated, never hand-edited, so it cannot drift from
 * what the tools actually reason about.
 *
 *   node scripts/gen-omnistudio-docs.mjs          write the document
 *   node scripts/gen-omnistudio-docs.mjs --check  exit 1 when it is stale
 *
 * Requires a build (`pnpm -r build`): it reads the compiled catalog.
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const out = join(root, 'docs', 'omnistudio', 'element-catalog.md');

export const renderCatalogDoc = (catalog) => {
  const esc = (s) => String(s).replace(/\|/g, '\\|');
  const lines = [
    '# OmniStudio element catalog',
    '',
    '<!-- GENERATED by scripts/gen-omnistudio-docs.mjs from packages/extractors/src/omnistudio/catalog.ts. Do not edit by hand. -->',
    '',
    'Every OmniScript element type and Integration Procedure step type sf-intelligence knows, with how it touches the',
    'data JSON (**role**), what it does at runtime (**effects**), and the configuration keys whose values name another',
    'component or a data key (**reference keys** — the keys the reference scan reads). Every OmniStudio tool reads this',
    'catalog; a type it does not list is handled conservatively (an OmniScript element holds a value under its name',
    'unless its type ends in "Action"; an Integration Procedure step\'s output is opaque) — never assumed to do nothing.',
    '',
    'Alternate spellings (DataRaptor ↔ Data Mapper, REST ↔ HTTP) map to the canonical type; tools keep the spelling the',
    'metadata used in their output.',
    '',
    '| Type | Also spelled | OmniScript role | IP role | Effects | Reference keys | What it does |',
    '|---|---|---|---|---|---|---|',
  ];
  for (const e of catalog) {
    lines.push(
      `| ${esc(e.type)} | ${esc(e.aliases.join(', ') || '—')} | ${e.scriptRole ?? '—'} | ${e.ipRole ?? '—'} | ${esc(e.effects.join(', '))} | ${esc(e.referenceKeys.map((k) => `\`${k}\``).join(' ') || '—')} | ${esc(e.doc)} |`,
    );
  }
  lines.push('', `${catalog.length} types.`, '');
  return lines.join('\n');
};

const main = async () => {
  const catalogModule = join(root, 'packages/extractors/dist/src/omnistudio/catalog.js');
  if (!existsSync(catalogModule)) {
    console.error('gen-omnistudio-docs: build first (pnpm -r build) — compiled catalog not found');
    process.exit(2);
  }
  const { OMNI_ELEMENT_CATALOG } = await import(pathToFileURL(catalogModule).href);
  const doc = renderCatalogDoc(OMNI_ELEMENT_CATALOG);
  if (process.argv.includes('--check')) {
    const current = existsSync(out) ? readFileSync(out, 'utf8') : '';
    if (current !== doc) {
      console.error('gen-omnistudio-docs: docs/omnistudio/element-catalog.md is stale — run `pnpm docs:omnistudio`');
      process.exit(1);
    }
    console.log('gen-omnistudio-docs: element catalog doc is current');
    return;
  }
  mkdirSync(dirname(out), { recursive: true });
  writeFileSync(out, doc, 'utf8');
  console.log(`gen-omnistudio-docs: wrote ${out} (${OMNI_ELEMENT_CATALOG.length} types)`);
};

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) await main();
