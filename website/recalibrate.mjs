/* =========================================================================
 * 4. lastmod.json — each page's last real content change, from git history.
 *
 * Cloudflare Pages builds from a shallow clone, where `git log -- <file>`
 * returns HEAD for every file: every sitemap <lastmod> read the same
 * 2026-10-03T18:48:27Z. So the dates are computed HERE, from the full-history
 * local repo, and committed. The build only reads this file; a page that is not
 * in it gets no <lastmod> at all (omitting beats stamping the deploy date).
 * ======================================================================= */
const PAGES_DIR = path.join(SITE, "src/pages");
const lastmodPath = path.join(dataDir, "lastmod.json");
const gitOut = (args) => execSync(`git ${args}`, { cwd: SITE, encoding: "utf8", stdio: ["ignore", "pipe", "ignore"] }).trim();
let shallow = true;
try { shallow = gitOut("rev-parse --is-shallow-repository") !== "false"; } catch { /* no git: treat as shallow */ }
if (shallow) {
  warn("git history is shallow or missing; src/data/lastmod.json left unchanged (never stamp HEAD for every page).");
} else {
  const routes = {};
  const walkPages = (dir) => {
    for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
      const full = path.join(dir, e.name);
      if (e.isDirectory()) { walkPages(full); continue; }
      if (!/\.(astro|md|mdx)$/.test(e.name) || e.name.startsWith("_") || e.name.includes("[")) continue;
      const rel = path.relative(PAGES_DIR, full).replace(/\\/g, "/").replace(/\.(astro|md|mdx)$/, "");
      if (rel === "404") continue;
      const route = "/" + rel.replace(/(^|\/)index$/, "");
      const iso = gitOut(`log -1 --format=%cI -- "${full}"`);
      if (iso) routes[route.replace(/\/$/, "") || "/"] = new Date(iso).toISOString();
    }
  };
  walkPages(PAGES_DIR);
  // Markdown guides (src/content/guides/<section>/<name>.md) render at
  // /<section>/<name> through a dynamic [slug] route the walk above skips.
  const GUIDES_DIR = path.join(SITE, "src/content/guides");
  if (fs.existsSync(GUIDES_DIR)) {
    for (const section of fs.readdirSync(GUIDES_DIR, { withFileTypes: true })) {
      if (!section.isDirectory()) continue;
      for (const f of fs.readdirSync(path.join(GUIDES_DIR, section.name))) {
        if (!/\.mdx?$/.test(f)) continue;
        const full = path.join(GUIDES_DIR, section.name, f);
        const iso = gitOut(`log -1 --format=%cI -- "${full}"`);
        if (iso) routes[`/${section.name}/${f.replace(/\.mdx?$/, "")}`] = new Date(iso).toISOString();
      }
    }
  }
  const sorted = Object.fromEntries(Object.entries(routes).sort(([a], [b]) => a.localeCompare(b)));
  fs.writeFileSync(lastmodPath, JSON.stringify(sorted, null, 2) + "\n");
  log(`• lastmod dates:                ${Object.keys(sorted).length} routes from git history`);
}

