const normalizeSeoText = (s) => s.replace(/[–—]/g, "-").replace(/…/g, "...");

/**
 * A tool's catalog summary: whole sentences only.
 *
 * The previous one-liner cut at the first ". " and then hard-sliced at 165
 * characters, so 111 of 226 entries in llms-full.txt (the file published for
 * verbatim machine citation) ended mid-word with "...". Now: split on real
 * sentence ends (not after e.g. / i.e. / vs. / etc. / a dotted API name), keep
 * up to two sentences inside ~300 characters, and when the FIRST sentence alone
 * is longer than that, drop its parenthetical asides and then end it at its last
 * top-level clause boundary (" — ", "; ", ": ", ", ") instead of mid-word.
 */
const SUMMARY_MAX = 300;
const ABBREV = /(?:\be\.g|\bi\.e|\bvs|\betc|\bcf|\bapprox|\bincl|\bNo)\.$/i;
function splitSentences(text) {
  const out = [];
  let start = 0;
  let depth = 0; // ( [ depth — never end a sentence inside an aside
  let tick = false; // inside `code`
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (c === "`") tick = !tick;
    if (tick) continue;
    if (c === "(" || c === "[") depth++;
    else if ((c === ")" || c === "]") && depth > 0) depth--;
    if (depth > 0 || !/[.!?]/.test(c)) continue;
    const next = text[i + 1];
    if (next !== undefined && next !== " ") continue; // "sfi.resolve", "0.4.0"
    const head = text.slice(start, i + 1);
    if (ABBREV.test(head)) continue;
    const after = text.slice(i + 1).trimStart();
    if (after && !/^[A-Z`"'(\[*_]/.test(after)) continue; // "... etc. and more"
    out.push(head.trim());
    start = i + 1;
  }
  const rest = text.slice(start).trim();
  if (rest) out.push(rest);
  return out;
}
/** Remove balanced (...) asides that sit outside backticks. */
function dropParentheticals(s) {
  let out = "";
  let depth = 0;
  let tick = false;
  for (const c of s) {
    if (c === "`" && depth === 0) tick = !tick;
    if (!tick && c === "(") { depth++; continue; }
    if (!tick && c === ")" && depth > 0) { depth--; continue; }
    if (depth === 0) out += c;
  }
  // A paired " — … — " is an aside too: "X, Y — detail about Y — and Z".
  // Replaced by a comma: in a list the dash pair stands where a comma would.
  out = out.replace(/ — [^—]+? — /g, ", ");
  return out.replace(/\s+([,.;:])/g, "$1").replace(/,(\s*,)+/g, ",").replace(/\s{2,}/g, " ").trim();
}
/** Cut at the last top-level clause boundary at or before `max`. */
function clauseCut(s, max) {
  let tick = false;
  let depth = 0;
  let best = { strong: -1, comma: -1 };
  for (let i = 0; i < Math.min(s.length, max); i++) {
    const c = s[i];
    if (c === "`") tick = !tick;
    if (tick) continue;
    if (c === "(" || c === "[") depth++;
    else if ((c === ")" || c === "]") && depth > 0) depth--;
    if (depth > 0) continue;
    if (s.startsWith(" — ", i) || s.startsWith(" - ", i) || s.startsWith("; ", i) || s.startsWith(": ", i)) best.strong = i;
    else if (s.startsWith(", ", i)) best.comma = i;
  }
  const at = best.strong > 60 ? best.strong : best.comma > 60 ? best.comma : -1;
  if (at === -1) return null;
  return s.slice(0, at).replace(/[,;:\s—-]+$/, "") + ".";
}
const summaryStats = { whole: 0, trimmedAsides: 0, clause: 0, wordCut: 0 };
function summarize(description) {
  const sentences = splitSentences(description);
  let first = sentences[0] ?? description;
  if (!/[.!?]$/.test(first)) first += ".";
  if (first.length <= SUMMARY_MAX) {
    let s = first;
    const second = sentences[1];
    if (second && (s + " " + second).length <= SUMMARY_MAX && !/^(Args|Example|Returns? shape|Input)\b/i.test(second)) s += " " + second;
    summaryStats.whole++;
    return normalizeSeoText(s);
  }
  const lean = dropParentheticals(first);
  if (lean.length <= SUMMARY_MAX) { summaryStats.trimmedAsides++; return normalizeSeoText(lean); }
  const cut = clauseCut(lean, SUMMARY_MAX);
  if (cut) { summaryStats.clause++; return normalizeSeoText(cut); }
  summaryStats.wordCut++;
  return normalizeSeoText(lean.slice(0, SUMMARY_MAX).replace(/\s+\S*$/, "") + "...");
}

